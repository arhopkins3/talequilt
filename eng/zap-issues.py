#!/usr/bin/env python3
"""Turn new ZAP alerts into GitHub issues, and close the issues of alerts that have gone (ADR 0021, build 3b).

Reads the JSON report the ZAP API scan wrote and the rules file that gives each plugin id its verdict. An entry in
the rules file means a person judged that alert, so a listed WARN or IGNORE opens nothing. Every other alert of Low
risk or above (an unlisted one, or a FAIL that has just failed the run) gets one open issue, titled with the plugin
id so a repeat run finds it instead of opening another; an issue whose alert no longer appears is closed with a
comment. Without this, a new warning sits unread in an artifact.

Usage: zap-issues.py <zap-report.json> <rules.tsv> <run url> [--dry-run]
Needs the gh CLI and GH_TOKEN with issues: write. Prints what it does; with --dry-run, prints what it would do.
"""

import json
import re
import subprocess
import sys

LABEL = "zap"
RISK = {0: "informational", 1: "low", 2: "medium", 3: "high"}


def sh(args: list[str], dry: bool) -> str:
    if dry:
        print("would run:", " ".join(args))
        return ""
    return subprocess.run(args, check=True, capture_output=True, text=True).stdout


def read_rules(path: str) -> dict[str, str]:
    verdicts: dict[str, str] = {}
    with open(path, encoding="utf-8") as f:
        for line in f:
            if not line.strip() or line.startswith("#"):
                continue
            parts = line.rstrip("\n").split("\t")
            if len(parts) >= 2:
                verdicts[parts[0].strip()] = parts[1].strip().upper()
    return verdicts


def read_alerts(path: str) -> dict[str, dict]:
    with open(path, encoding="utf-8") as f:
        report = json.load(f)
    alerts: dict[str, dict] = {}
    for site in report.get("site", []):
        for a in site.get("alerts", []):
            alerts[str(a["pluginid"])] = a
    return alerts


def title_for(a: dict) -> str:
    return f"ZAP: {a['name']} [{a['pluginid']}]"


def open_issues(dry: bool) -> dict[str, dict]:
    if dry:
        return {}
    out = sh(["gh", "issue", "list", "--label", LABEL, "--state", "open", "--limit", "200",
              "--json", "number,title"], dry)
    found: dict[str, dict] = {}
    for issue in json.loads(out or "[]"):
        t = issue["title"]
        if t.endswith("]") and "[" in t:
            found[t[t.rfind("[") + 1:-1]] = issue
    return found


def plain(html: str) -> str:
    """ZAP writes its descriptions as HTML paragraphs; the issue wants plain text."""
    text = re.sub(r"</p>\s*<p>", "\n\n", html or "")
    return re.sub(r"<[^>]+>", "", text).strip()


def body_for(a: dict, run_url: str) -> str:
    instance = (a.get("instances") or [{}])[0]
    where = f"{instance.get('method', '')} {instance.get('uri', '')}".strip()
    return "\n".join([
        f"**Risk:** {a.get('riskdesc', RISK.get(int(a.get('riskcode', 0)), '?'))}  ",
        f"**Instances:** {a.get('count', len(a.get('instances', [])))}  ",
        f"**First seen at:** {where}",
        "",
        plain(a.get("desc", "")),
        "",
        "**Suggested fix (from ZAP):**",
        "",
        plain(a.get("solution", "")),
        "",
        f"Opened by the staging ZAP scan of [this Deploy run]({run_url}). Fix it, or record a verdict for plugin "
        f"`{a['pluginid']}` in `.zap/api-rules.tsv` with the reason; the issue closes itself when the alert goes.",
        "",
        "---",
        "_Generated by [Claude Code](https://claude.ai/code)_",
    ])


def main() -> int:
    if len(sys.argv) < 4:
        print(__doc__)
        return 2
    report_path, rules_path, run_url = sys.argv[1:4]
    dry = "--dry-run" in sys.argv

    verdicts = read_rules(rules_path)
    alerts = read_alerts(report_path)
    actionable = {pid: a for pid, a in alerts.items()
                  if int(a.get("riskcode", 0)) >= 1 and verdicts.get(pid) not in ("IGNORE", "WARN")}

    sh(["gh", "label", "create", LABEL, "--force", "--color", "B60205",
        "--description", "Opened by the staging ZAP scan"], dry)
    existing = open_issues(dry)

    for pid, a in sorted(actionable.items()):
        if pid in existing:
            print(f"kept: #{existing[pid]['number']} {title_for(a)}")
            continue
        sh(["gh", "issue", "create", "--title", title_for(a), "--label", LABEL, "--body", body_for(a, run_url)], dry)
        print(f"opened: {title_for(a)}")

    for pid, issue in sorted(existing.items()):
        if pid not in actionable:
            sh(["gh", "issue", "close", str(issue["number"]), "--comment",
                f"The alert no longer appears in the staging ZAP scan of {run_url}.\n\n---\n"
                "_Generated by [Claude Code](https://claude.ai/code)_"], dry)
            print(f"closed: #{issue['number']} {issue['title']}")

    print(f"{len(actionable)} alert(s) need attention; {len(alerts) - len(actionable)} judged in the rules file or informational.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
